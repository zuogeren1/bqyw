package io.github.zuogeren.bqyw

import kotlin.math.roundToInt

/**
 * 基准坐标（2800×1260）→ 实际画面坐标。
 *
 * 游戏按**高度**铺满、横向不留黑边；并且**锚边挂在屏幕边上**，不是挂在 2800 宽的基准画布上。
 * 三条锚边（2376×1080 实拍图、边距 0 直接量出来的 ox_eff）：
 *
 * | 组   | 控件                             | ox_eff | 公式                     |
 * |------|----------------------------------|--------|--------------------------|
 * | 左锚 | 顶部标题、敌人信息、今日好运     | 0      | [lpx] = v·s              |
 * | 居中 | 5 张卡、战力点表、放弃确认弹窗   | −12    | [px]  = ox + v·s         |
 * | 右锚 | 抽牌、撤离、铭牌库、轮次条       | −24    | [rpx] = w − (2800−v)·s   |
 *
 * 20:9 上三者恒等（w = 2800·s、ox = 0），所以 1.2.0 之前完全看不出来；一换比例就分叉：
 * 11:5 上左右锚各差 12 px —— 点击还落在按钮里，但 [Layout] 自检按居中偏移折回，
 * 边距凭空多算 14 px 直接停手。
 *
 * 其余两条：
 *
 *   s  = h / 1260          （只按高度算，不看宽度）
 *   ox = (w − 2800·s) / 2  （比 20:9 窄时是负数 = 两侧被裁，宽时是正数）
 *   oy = 0                 （纵向永远贴边，实测 11 个特征残差 rms 0.30 px，没有黑边）
 *
 * 改之前用的是 min(w/2800, h/1260) + 上下留黑边，在 20:9 上两者完全等价，
 * 一换比例就整体偏：11:5 上老写法 s=0.8486（差 1%）、oy=5.4（凭空多出黑边），
 * 到屏幕右侧累积 11.6 px —— 轮次徽章窗口只有 38 px 宽，直接读错。
 */
class Fit(val w: Int, val h: Int) {

    /** 基准像素 → 实际像素的缩放：**只跟高度有关**。 */
    val s: Float = h / BASE_H

    /** 居中锚的水平偏移：比 20:9 窄时是负数（两侧被裁掉一部分）。 */
    val ox: Float = (w - BASE_W * s) / 2f

    /** 纵向永远贴边，实测恒为 0。留这个字段是为了日志和对照，别再拿它算黑边。 */
    val oy: Float = 0f

    /** 居中画的东西：卡牌行、战力点/奖励点表、放弃确认弹窗。 */
    fun px(v: Float): Int = (ox + v * s).roundToInt()

    /** 贴左边画的东西：基准 0 落在屏幕 0。 */
    fun lpx(v: Float): Int = (v * s).roundToInt()

    /** 贴右边画的东西：基准 2800 落在屏幕 w。 */
    fun rpx(v: Float): Int = (w - (BASE_W - v) * s).roundToInt()

    /** [rpx] 的逆：屏幕 x → 基准 x。自检要用它把量到的坐标折回基准再算边距。 */
    fun runpx(x: Float): Float = BASE_W - (w - x) / s

    fun py(v: Float): Int = (v * s).roundToInt()

    companion object {
        /** 界面标定用的基准分辨率：2800×1260，20:9。 */
        const val BASE_W = 2800f
        const val BASE_H = 1260f
    }
}
